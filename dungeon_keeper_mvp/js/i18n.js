class I18n {
  constructor() {
    this.currentLang = "ru";
    this.locales = LOCALES;
    this.listeners = [];
  }

  init(lang) { this.setLanguage(lang || "ru", false); }

  setLanguage(lang, notify = true) {
    if (!this.locales[lang]) lang = "ru";
    this.currentLang = lang;
    if (notify) for (const cb of this.listeners) cb(lang);
  }

  getLanguage() { return this.currentLang; }

  t(key, ...args) {
    const dict = this.locales[this.currentLang] || this.locales.ru;
    let str = dict[key] ?? this.locales.ru[key] ?? key;
    for (let i = 0; i < args.length; i++) {
      str = str.replace(`{${i}}`, args[i]);
    }
    return str;
  }

  onChange(cb) { this.listeners.push(cb); }
  offChange(cb) { const i = this.listeners.indexOf(cb); if (i !== -1) this.listeners.splice(i, 1); }
}

export const i18n = new I18n();
export function t(key, ...args) { return i18n.t(key, ...args); }